class TestMapping:
    @pytest.mark.parametrize("phones,expected", CASES)
    def test_cases(self, phones, expected):
        moras, warns = _moras(phones)
        assert _labels(moras) == expected, warns


class TestCodaWordConstraint:
    def test_cross_word_n_not_grabbed(self):
        # 可能：kʰ+o | n+o+ŋ（词界）→ ke, neng；无词界约束会得 kon
        phones = [
            ("kʰ", 0.0, 0.08),
            ("o˨˩˦", 0.08, 0.3),
            ("n", 0.3, 0.36),
            ("o˧˥", 0.36, 0.52),
            ("ŋ", 0.52, 0.6),
        ]
        words = [(0.0, 0.3), (0.3, 0.6)]
        moras, warns = _moras(phones, words=words)
        assert _labels(moras) == ["ke", "neng"]

    def test_ng_always_coda(self):
        # ŋ 无词界也吞入（普通话无 ŋ 声母）
        phones = [("tɕʰ", 0, 0.08), ("i˥", 0.08, 0.25), ("ŋ", 0.25, 0.4)]
        moras, warns = _moras(phones)
        assert _labels(moras) == ["qing"]


class TestZeroInitialTiming:
    def test_glottal_stop_is_real_consonant(self):
        moras, _ = _moras([("ʔ", 0.0, 0.09), ("a˥˩", 0.09, 0.47)])
        m = moras[0]
        assert m.romaji == "a"
        assert m.consonant_end == pytest.approx(0.09)

    def test_virtual_30ms_consonant(self):
        moras, _ = _moras([("a˥", 0.0, 0.4)])
        m = moras[0]
        assert m.consonant_end == pytest.approx(min(0.030, 0.4 * 0.2))

    def test_vowel_with_coda_cons_end_absent(self):
        moras, _ = _moras([("kʰ", 0, 0.08), ("a˥˩", 0.08, 0.35), ("n", 0.35, 0.45)])
        assert moras[0].consonant_end == pytest.approx(0.08)


class TestWarnings:
    def test_skips_and_drops(self):
        phones = [
            ("spn", 0, 0.1),
            ("ʈʂ", 0.1, 0.18),
            ("ow˥", 0.18, 0.4),
            ("tɕ", 0.4, 0.47),  # 孤辅音（片尾无元音）
        ]
        moras, warns = _moras(phones)
        assert _labels(moras) == ["zhou"]
        assert any("孤辅音" in w for w in warns)
        assert any("spn" in w for w in warns)
