from jrh.importers.mfa_zh import Phone, phones_to_moras


def _moras(
    phones: list[tuple[str, float, float]],
    words: list[tuple[float, float]] | None = None,
):
    moras, warns = phones_to_moras([Phone(t, a, b) for t, a, b in phones], word_ranges=words)
    return moras, warns


def _labels(moras) -> list[str]:
    return [m.romaji for m in moras]


